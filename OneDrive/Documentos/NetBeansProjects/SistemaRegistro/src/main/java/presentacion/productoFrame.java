    public void cargarDatos() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nombre");
        model.addColumn("Precio");
        model.addColumn("Codigo");
        for (Producto p : servicio.ListarProductos()) {
            Object[] fila = {p.getId(), p.getNombre(), p.getPrecio(), p.getCodigo()};
            model.addRow(fila);
        }
        tblProducto.setModel(model);

    }

    private void llenarFormularioDesdeTabla() {
        int filaSeleccionada = tblProducto.getSelectedRow();
        if (filaSeleccionada >= 0) {

            String nombre = tblProducto.getValueAt(filaSeleccionada, 1).toString();
            String precio = tblProducto.getValueAt(filaSeleccionada, 2).toString();
            String codigo = tblProducto.getValueAt(filaSeleccionada, 3).toString();

            nomTxtField.setText(nombre);
            precioTxtField.setText(precio);
            codigoTxtField.setText(codigo);
        }
    }

    public void agregar() {
        // Si el formulario esta lleno
        if (ValidarFormulario()) {
            System.out.println("Intentando registrar");

            double precio = 0.0;
            precio = Double.parseDouble(precioTxtField.getText());
            Producto nuevoProducto = new Producto(nomTxtField.getText(), precio,
                    codigoTxtField.getText());

            servicio.agregarNuevoProducto(nuevoProducto);
            cargarDatos();

        } else {
            System.out.println("Falta llenar un input");
            // Mostrar alerta de que llene el formulario

        }

    }

    public void editar() {
        int fila = tblProducto.getSelectedRow();
        if (fila >= 0) {

            int id = (int) tblProducto.getValueAt(fila, 0);

            String nuevoNombre = nomTxtField.getText();
            double nuevoPrecio = Double.parseDouble(precioTxtField.getText());
            String nuevoCodigo = codigoTxtField.getText();

            Producto productoEditado = new Producto(nuevoNombre, nuevoPrecio, nuevoCodigo);
            productoEditado.setId(id);

            servicio.ActualizarProducto(productoEditado);

            cargarDatos();
        } else {
            System.out.println("Seleccione una fila para editar.");
        }
    }

    private void vaciarCampos() {

        nomTxtField.setText("");
        precioTxtField.setText("");
        codigoTxtField.setText("");
    }

    public void eliminar() {
        int fila = tblProducto.getSelectedRow();
        if (fila >= 0) {
            int id = (int) tblProducto.getValueAt(fila, 0);

            int confirm = JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar este producto?",
                    "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                servicio.EliminarProductoPorId(id);
                cargarDatos();
                vaciarCampos();

            }
        } else {
            System.out.println("Seleccione una fila para eliminar.");
        }
    }

