    private boolean ValidarFormulario() {
        // pintar los bordes utilizando operador ternario
        nomTxtField.setBorder(nomTxtField.getText().isEmpty() ? bordeRojo : bordeNegro);
        precioTxtField.setBorder(precioTxtField.getText().isEmpty() ? bordeRojo : bordeNegro);
        codigoTxtField.setBorder(codigoTxtField.getText().isEmpty() ? bordeRojo : bordeNegro);

        return !(nomTxtField.getText().isEmpty() || precioTxtField.getText().isEmpty()
                || codigoTxtField.getText().isEmpty());
    }

